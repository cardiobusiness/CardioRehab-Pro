import { test } from "node:test";
import assert from "node:assert/strict";
import { HeartRateMonitor, type MonitorSnapshot } from "../src/sensors/heartRateMonitor.ts";
import { SIMULATED_DEVICE_ID, SimulatedBleTransport } from "../src/sensors/simulatedBle.ts";
import { isCurrentReading } from "../src/sensors/heartRateSeries.ts";

test("simulator discovers, connects, decodes both BPM widths and clears timers on dispose", async context => {
  context.mock.timers.enable({ apis: ["setTimeout", "setInterval", "Date"], now: 10000 });
  const transport = new SimulatedBleTransport();
  let snapshot: MonitorSnapshot = { status: "idle", devices: [], rejected: 0 };
  const monitor = new HeartRateMonitor(transport, next => { snapshot = next; });
  await monitor.scan();
  context.mock.timers.tick(250);
  assert.equal(snapshot.devices[0].id, SIMULATED_DEVICE_ID);
  assert.match(snapshot.devices[0].name!, /SIMULADO/);
  assert.equal(snapshot.status, "scanning");
  await monitor.connect(SIMULATED_DEVICE_ID);
  context.mock.timers.tick(0);
  const first = snapshot.reading!;
  assert.equal(first.bpm, 82);
  assert.equal(first.deviceId, SIMULATED_DEVICE_ID);
  assert.equal(first.contact, "detected");
  context.mock.timers.tick(1000);
  assert.ok(snapshot.reading!.bpm > first.bpm);
  assert.equal(snapshot.rejected, 0);
  assert.ok(snapshot.reading!.rrIntervalsMs[0] > 0);
  await monitor.dispose();
  const last = snapshot;
  await transport.destroy();
  context.mock.timers.tick(60000);
  assert.equal(snapshot, last);
});
test("pausing makes signal stale and resuming supplies fresh data", async context => {
  context.mock.timers.enable({ apis: ["setTimeout", "setInterval", "Date"], now: 10000 });
  const transport = new SimulatedBleTransport();
  let snapshot: MonitorSnapshot = { status: "idle", devices: [], rejected: 0 };
  const monitor = new HeartRateMonitor(transport, next => { snapshot = next; });
  await monitor.connect(SIMULATED_DEVICE_ID);
  context.mock.timers.tick(0);
  assert.equal(isCurrentReading(snapshot.reading, Date.now()), true);
  transport.setPaused(true);
  context.mock.timers.tick(6000);
  assert.equal(snapshot.status, "streaming");
  assert.equal(isCurrentReading(snapshot.reading, Date.now()), false);
  transport.setPaused(false);
  context.mock.timers.tick(1000);
  assert.equal(isCurrentReading(snapshot.reading, Date.now()), true);
  await monitor.dispose();
  await transport.destroy();
});
test("simulated link loss reconnects to the same device through the real controller", async context => {
  context.mock.timers.enable({ apis: ["setTimeout", "setInterval", "Date"], now: 10000 });
  const transport = new SimulatedBleTransport();
  let snapshot: MonitorSnapshot = { status: "idle", devices: [], rejected: 0 };
  const monitor = new HeartRateMonitor(transport, next => { snapshot = next; });
  await monitor.connect(SIMULATED_DEVICE_ID);
  context.mock.timers.tick(0);
  transport.simulateDisconnect();
  assert.equal(snapshot.status, "reconnecting");
  assert.equal(snapshot.reading, undefined);
  context.mock.timers.tick(1000);
  // Reconnect awaits native-style promises; drain those before ticking packets.
  for (let index = 0; index < 12; ++index) await Promise.resolve();
  assert.equal(snapshot.status, "streaming");
  context.mock.timers.tick(0);
  assert.equal(snapshot.reading!.deviceId, SIMULATED_DEVICE_ID);
  await monitor.dispose();
  await transport.destroy();
});
